// Post-build pass over the static export (`npm run build` → postbuild). The
// asset server serves the pages without the Worker (run_worker_first in
// wrangler.jsonc: /api/* and the MTA-STS policy only), so what the Worker used
// to do per request happens here, once:
//   1. /en/ pages get <html lang="en"> — one root layout exports "nb";
//      pages Next left without the body font's <link rel="preload"> (the 404)
//      get the front page's — with display: 'optional' a page without it
//      renders in the system monospace (app/layout.tsx);
//   2. every page gets its hash CSP atop <head>, after the charset and ahead
//      of any script (withMetaCsp from src/csp.ts: its inline scripts' hashes);
//   3. /favicon.ico — a copy of the build-time /icons/favicon.ico (feed
//      readers and unfurlers ask for it directly);
//   4. out/_redirects (public/_redirects + generated lines) gains a 301 from
//      each page's slash-less path — the asset server's own is a 307.
// Any failure exits non-zero and fails the build: no deploy without a CSP.
// `npm run check:csp` (scripts/check-csp.mjs) re-checks the result.
import { appendFileSync, copyFileSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { pathToFileURL } from 'node:url'
import { withMetaCsp } from '../src/csp.ts'

const OUT = 'out'

export function htmlFiles(dir = OUT) {
  return readdirSync(dir, { recursive: true })
    .filter((f) => f.endsWith('.html'))
    .map((f) => join(dir, f))
}

// out/blogg/velkommen/index.html → /blogg/velkommen/ (null for 404.html etc.).
export function pagePath(file, dir = OUT) {
  const rel = relative(dir, file).split(sep).join('/')
  if (rel === 'index.html') return '/'
  return rel.endsWith('/index.html') ? `/${rel.slice(0, -'index.html'.length)}` : null
}

// The body font's preload links, as Next emits them on index.html.
const FONT_PRELOAD_RE = /<link rel="preload" href="[^"]+\.woff2" as="font"[^>]*>/g

export function fontPreloads(html) {
  return html.match(FONT_PRELOAD_RE) ?? []
}

// Adds `links` after the viewport <meta> (else before </head>) when the page
// has no font preload of its own.
export function withFontPreload(html, links) {
  if (fontPreloads(html).length > 0) return html
  const viewport = /<meta name="viewport"[^>]*>/.exec(html)
  if (viewport) {
    const at = viewport.index + viewport[0].length
    return html.slice(0, at) + links.join('') + html.slice(at)
  }
  if (!html.includes('</head>')) throw new Error('no <head> to add the font preload to')
  return html.replace('</head>', `${links.join('')}</head>`)
}

// Limits from the Workers static-assets docs: 2,000 static redirects,
// 1,000 characters a line.
export function slashRedirects(paths) {
  const lines = paths
    .filter((p) => p !== '/' && !['/404/', '/_not-found/'].includes(p))
    .sort()
    .map((p) => `${p.slice(0, -1)} ${p} 301`)
  if (lines.length > 1900) throw new Error(`${lines.length} slash redirects — near the 2,000 static-redirect limit`)
  return lines
}

async function main() {
  const files = htmlFiles()
  if (files.length === 0) throw new Error(`no HTML in ${OUT}/ — run next build first`)
  const fonts = fontPreloads(readFileSync(join(OUT, 'index.html'), 'utf8'))
  if (fonts.length === 0) throw new Error('index.html has no font preload — app/layout.tsx lost `preload: true`?')
  const paths = []
  for (const file of files) {
    let html = withFontPreload(readFileSync(file, 'utf8'), fonts)
    const path = pagePath(file)
    if (path) paths.push(path)
    if (path === '/en/' || path?.startsWith('/en/')) {
      if (!html.includes('<html lang="nb"') && !html.includes('<html lang="en"')) {
        throw new Error(`${file}: no <html lang="nb"> to switch to "en"`)
      }
      html = html.replace('<html lang="nb"', '<html lang="en"')
    }
    writeFileSync(file, await withMetaCsp(html))
  }

  copyFileSync(join(OUT, 'icons', 'favicon.ico'), join(OUT, 'favicon.ico'))

  const redirects = slashRedirects(paths)
  appendFileSync(
    join(OUT, '_redirects'),
    `\n# Generated by scripts/finalize-export.mjs: slash-less page paths.\n${redirects.join('\n')}\n`,
  )
  console.log(`finalize-export: ${files.length} pages with a CSP <meta> and the font preload, ${redirects.length} slash redirects`)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(`finalize-export: ${err.message}`)
    process.exit(1)
  })
}
